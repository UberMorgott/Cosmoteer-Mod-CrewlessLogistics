param(
    [string]$GameRoot = 'D:\Steam\steamapps\common\Cosmoteer',
    [string]$CatalogPath = (Join-Path $PSScriptRoot '..\docs\device-catalog.json')
)
$ErrorActionPreference = 'Stop'
$projectRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
. (Join-Path $PSScriptRoot 'Generate-PerimeterPorts.ps1')
if (-not (Test-Path -LiteralPath $CatalogPath)) { throw 'Build the enabled native device catalog before generating compatibility.' }
$catalog = Get-Content -LiteralPath $CatalogPath -Raw | ConvertFrom-Json
$coveragePath = Join-Path $projectRoot 'docs\consumer-coverage.json'
$vanilla = @($catalog.parts | Where-Object { $_.modId -eq 'vanilla' -and $_.classification -eq 'consumer' })
$modded = @($catalog.parts | Where-Object { $_.modId -ne 'vanilla' -and $_.classification -eq 'consumer' } | Sort-Object id)
$components = [Text.StringBuilder]::new()
$moddedComponents = [Text.StringBuilder]::new()
$actions = [Text.StringBuilder]::new()
foreach ($text in @($components, $moddedComponents, $actions)) { [void]$text.AppendLine('// Generated by tools/Generate-ConsumerCoverage.ps1; native rules only.') }
# mod.rules inherits this whole list: Actions : <generated.actions.rules>/Actions [...]
[void]$actions.AppendLine('Actions'); [void]$actions.AppendLine('[')
$vanillaMap = @(); $moddedMap = @(); $moddedIndex = 0
function Get-PortableWorkshopPartPath([string]$canonicalPath) {
    if ($canonicalPath -notmatch '^<([^>]+)>(/.*)$') { throw "Invalid native part path: $canonicalPath" }
    $sourceFile = $Matches[1]
    $groupPath = $Matches[2]
    # Native ModAddBaseAction resolves paths against Data/cosmoteer.rules.
    # Three parents reach steamapps for standard Steam Workshop installations.
    $relativeFile = [IO.Path]::GetRelativePath([IO.Path]::Combine($GameRoot, 'Data'), $sourceFile).Replace('\', '/')
    if ($relativeFile -notmatch '^\.\./\.\./\.\./workshop/content/799600/\d+/[^<>]+\.rules$') {
        throw "Cannot package portable native compatibility for this mod location: $sourceFile. Expected the game's Steam library Workshop directory."
    }
    return "<$relativeFile>$groupPath"
}
foreach ($device in @($vanilla) + @($modded)) {
    $isVanilla = $device.modId -eq 'vanilla'
    $name = if ($isVanilla) { $device.id -replace '^cosmoteer\.', '' } else { $device.id }
    $group = if ($isVanilla) { $name } else { "Device$moddedIndex" }
    $partPath = if ($isVanilla) { "<./Data/ships/terran/$name/$name.rules>/Part" } else { Get-PortableWorkshopPartPath $device.canonicalPartGroupPath }
    $target = if ($isVanilla) { "<ships/terran/$name/$name.rules>/Part/Components" } else { "$partPath/Components" }
    $receiver = [string]$device.receiverStorage
    $physicalIds = @($device.physicalStorageIds)
    if ($physicalIds.Count -ne 1) { throw "Consumer $($device.id) requires an explicit independent physical-store mapping." }
    $physical = [string]$physicalIds[0]
    $physicalMetadata = @($device.batteryStorages | Where-Object { $_.id -eq $physical })
    if ($physicalMetadata.Count -ne 1 -or $physicalMetadata[0].type -ne 'ResourceStorage' -or -not $physicalMetadata[0].values.MaxResources) { throw "Consumer $($device.id) has no native constant-capacity physical battery." }
    $capacity = [int]$physicalMetadata[0].values.MaxResources
    if ($capacity -lt 1000 -or $capacity % 1000) { throw "Consumer $($device.id) cannot accept exact native cells." }
    $edges = @(Get-CrewlessLogisticsPerimeterEdges $device)
    if ($edges.Count -eq 0) { throw "No cable-reachable perimeter edge for $($device.id)." }
    $body = [Text.StringBuilder]::new()
    $adapterBase = if ($isVanilla -and $name -eq 'engine_room') { 'engine_room_power.rules' } else { 'consumer_base.rules' }
    [void]$body.AppendLine("$group : <$adapterBase>/Components")
    [void]$body.AppendLine('{')
    if ($receiver -ne 'BatteryStorage') { [void]$body.AppendLine("    CrewlessLogisticsReceivingAggregate : ^/0/CrewlessLogisticsReceivingAggregate { ResourceStorages = [$receiver, CrewlessLogisticsReceivingBias] }") }
    # Mirror the vanilla crew battery consumer: AllowNonOperationalMinPriorityDelivery = false
    # means crew deliver only while its OperationalToggle is on (hyperdrives: FtlDrive spool-up).
    $crewConsumer = @($device.batteryReceivers | Select-Object -First 1)
    $acceptToggle = if ($crewConsumer.Count -and $crewConsumer[0].values.AllowNonOperationalMinPriorityDelivery -eq $false) { [string]$crewConsumer[0].references.OperationalToggle } else { $null }
    if ($acceptToggle) {
        [void]$body.AppendLine("    CrewlessLogisticsAcceptGate { Type = MultiToggle; Mode = All; Toggles = [CrewlessLogisticsToggle, $acceptToggle] }")
        [void]$body.AppendLine('    CrewlessLogisticsReceiver : ^/0/CrewlessLogisticsReceiver { OperationalToggle = CrewlessLogisticsAcceptGate }')
        [void]$body.AppendLine('    CrewlessLogisticsRoomInlet : ^/0/CrewlessLogisticsRoomInlet { ProxyToggle = CrewlessLogisticsAcceptGate }')
    }
    $ports = @(); $used = @{}
    foreach ($edge in $edges) {
        $x = [int]$edge.Location[0]; $y = [int]$edge.Location[1]; $direction = [string]$edge.Direction
        $thermal = @($device.thermalPorts | Where-Object { $_.direction -eq $direction -and $_.location[0] -eq $x -and $_.location[1] -eq $y } | Select-Object -First 1)
        $id = "CrewlessLogisticsPort_${direction}_${x}_${y}"
        if ($used.ContainsKey($id)) { throw "Duplicate generated electrical port ID on $($device.id): $id" }; $used[$id]=$true
        [void]$body.AppendLine("    $id : <common.rules>/ConsumerElectricPort { Location = [$x, $y]; Direction = $direction }")
        # Native Primary overlays show exact attachment markers during cable placement.
        # Do not add persistent room graphics for edges without a thermal socket.
        $ports += [ordered]@{component=$id;thermalComponent=$(if($thermal.Count){$thermal[0].id}else{$null});location=@($x,$y);direction=$direction;neighbor=@($edge.Neighbor);graphics=$null}
    }
    [void]$body.AppendLine('}')
    if ($isVanilla) {
        [void]$components.Append($body.ToString())
        [void]$actions.AppendLine("    { Action = AddBase; AddBaseTo = `"$target`"; BaseToAdd = &<consumers.rules>/$group; }")
    } else {
        [void]$moddedComponents.Append($body.ToString())
        [void]$actions.AppendLine("    { Action = AddBase; AddBaseTo = `"$target`"; BaseToAdd = &<modded-devices.rules>/$group; IgnoreIfNotExisting = true; }")
        $moddedIndex++
    }
    $crewReceiver = if (@($device.batteryReceivers).Count) { $device.batteryReceivers[0].references.Storage } else { $null }
    $entry = [ordered]@{part=$name;id=$device.id;path=$partPath;registryIndex=$device.registryIndex;modId=$device.modId;sourcePath=$device.sourcePath;backingStorage=$physical;receiverStorage=$receiver;originalCrewReceiver=$crewReceiver;acceptToggle=$acceptToggle;capacity=$capacity;geometry=[ordered]@{size=@($device.size);physicalRect=$device.physicalRect;prohibitRects=@($device.prohibitRects);prohibitSides=$device.prohibitSides;prohibits=@($device.prohibits);prohibitedBy=@($device.prohibitedBy)};ports=$ports;sourceSha256=(Get-FileHash -LiteralPath $device.sourcePath -Algorithm SHA256).Hash}
    if ($isVanilla) { $vanillaMap += $entry } else { $moddedMap += $entry }
}
# Reactors and the capacitor relay through one shared bus on every permitted perimeter edge.
$sources = [Text.StringBuilder]::new()
[void]$sources.AppendLine('// Generated by tools/Generate-ConsumerCoverage.ps1; native rules only.')
foreach ($device in @($catalog.parts | Where-Object { $_.modId -eq 'vanilla' -and $_.classification -in @('reactor','capacitor') } | Sort-Object registryIndex)) {
    $name = $device.id -replace '^cosmoteer\.', ''
    $adapter = if ($device.classification -eq 'capacitor') { 'capacitor.rules' } else { 'source-components.rules' }
    [void]$sources.AppendLine("$name : <$adapter>/Components"); [void]$sources.AppendLine('{')
    foreach ($edge in @(Get-CrewlessLogisticsPerimeterEdges $device)) {
        $x = [int]$edge.Location[0]; $y = [int]$edge.Location[1]; $direction = [string]$edge.Direction
        [void]$sources.AppendLine("    CrewlessLogisticsPort_${direction}_${x}_${y} : <common.rules>/BusElectricPort { Location = [$x, $y]; Direction = $direction }")
    }
    [void]$sources.AppendLine('}')
    [void]$actions.AppendLine("    { Action = AddBase; AddBaseTo = `"<ships/terran/$name/$name.rules>/Part/Components`"; BaseToAdd = &<sources.rules>/$name; }")
}
[void]$actions.AppendLine(']')
[IO.File]::WriteAllText((Join-Path $projectRoot 'mod\sources.rules'), $sources.ToString())
[IO.File]::WriteAllText((Join-Path $projectRoot 'mod\consumers.rules'), $components.ToString())
[IO.File]::WriteAllText((Join-Path $projectRoot 'mod\modded-devices.rules'), $moddedComponents.ToString())
[IO.File]::WriteAllText((Join-Path $projectRoot 'mod\generated.actions.rules'), $actions.ToString())
$unsupported=@($catalog.parts|Where-Object{$_.classification -eq 'unsupported'}|Select-Object id,modId,unsupportedReason)
$unsupported+=@($catalog.parts|Where-Object{$_.modId -ne 'vanilla' -and $_.classification -in @('reactor','capacitor')}|ForEach-Object{[pscustomobject]@{id=$_.id;modId=$_.modId;unsupportedReason='Modded source/storage adapter not generated.'}})
$report=[ordered]@{vanillaConsumerCount=$vanillaMap.Count;generatedActions=$vanillaMap.Count;moddedConsumerCount=$moddedMap.Count;moddedGeneratedActions=$moddedMap.Count;localPhysicalStorageOnly=$true;catalogSha256=(Get-FileHash -LiteralPath $CatalogPath -Algorithm SHA256).Hash;perimeterPolicy='All physical rectangular perimeter edges with a neighboring cable cell outside Size and outside applicable native prohibition rectangles; original doors preserved.';parts=$vanillaMap;moddedParts=$moddedMap;unsupported=$unsupported;limits='Native rules metadata only; mod DLL-only registrations/custom storage semantics need explicit mapping. Regenerate after enabled mods or versions change. Optional Workshop targets are portable relative to Data/cosmoteer.rules within the game Steam library; nonstandard external mod locations require an explicit portable integration.'}
[IO.File]::WriteAllText($coveragePath, ($report|ConvertTo-Json -Depth 18)+[Environment]::NewLine)
$totalPorts=@(@($vanillaMap)+@($moddedMap)|ForEach-Object{$_.ports}).Count
Write-Output "Generated $($vanillaMap.Count) vanilla + $($moddedMap.Count) enabled-mod consumers; $totalPorts permitted perimeter sockets; optional mod actions=$moddedIndex."
